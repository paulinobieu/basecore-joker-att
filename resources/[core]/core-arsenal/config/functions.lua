-----------------------------------------------------------------------------------------------------------------------------------------
-- VRP
-----------------------------------------------------------------------------------------------------------------------------------------
Tunnel = module("vrp","lib/Tunnel")
Proxy = module("vrp","lib/Proxy")
vRP = Proxy.getInterface("vRP")
-----------------------------------------------------------------------------------------------------------------------------------------
-- FUNCTIONS
-----------------------------------------------------------------------------------------------------------------------------------------
Functions = {}
-----------------------------------------------------------------------------------------------------------------------------------------
-- PASSPORT
-----------------------------------------------------------------------------------------------------------------------------------------
function Functions.Passport(source)
	return vRP.Passport(source)
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- HASPERMISSION
-----------------------------------------------------------------------------------------------------------------------------------------
function Functions.HasPermission(Passport,Permission)
	if not Passport then
		return false
	end

	if not Permission then
		return true
	end

	if type(Permission) == "table" then
		for _,Entry in ipairs(Permission) do
			if Functions.HasPermission(Passport,Entry) then
				return true
			end
		end
		return false
	end

	return (vRP.HasService(Passport,Permission) or vRP.HasPermission(Passport,Permission)) and true or false
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- TRYPAYMENT
-----------------------------------------------------------------------------------------------------------------------------------------
function Functions.TryPayment(Passport,Price)
	return vRP.PaymentBank(Passport,Price)
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- GENERATEITEM
-----------------------------------------------------------------------------------------------------------------------------------------
function Functions.GenerateItem(Passport,Item,Amount)
	return vRP.GenerateItem(Passport,Item,Amount,false)
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- NOTIFY
-----------------------------------------------------------------------------------------------------------------------------------------
function Functions.Notify(source,Kind,Message)
	if source then
		TriggerClientEvent("Notify",source,"Arsenal",Message,Kind or "amarelo",5000)
	else
		TriggerEvent("Notify","Arsenal",Message,Kind or "amarelo",5000)
	end
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- HEXTORGB
-----------------------------------------------------------------------------------------------------------------------------------------
function Functions.HexToRgb(Hex)
	if type(Hex) ~= "string" then return 1,67,187 end
	Hex = Hex:gsub("#","")
	if #Hex ~= 6 then return 1,67,187 end
	return tonumber(Hex:sub(1,2),16) or 1,tonumber(Hex:sub(3,4),16) or 67,tonumber(Hex:sub(5,6),16) or 187
end
