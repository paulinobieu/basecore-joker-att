-----------------------------------------------------------------------------------------------------------------------------------------
-- OPTIMIZATION
-----------------------------------------------------------------------------------------------------------------------------------------
local tonumber = tonumber
local tostring = tostring
local mathFloor = math.floor
local osTime = os.time
-----------------------------------------------------------------------------------------------------------------------------------------
-- VARIABLES
-- Uma operação de dinheiro por passaporte de cada vez. A trava é tomada antes
-- de qualquer validação que ceda o frame, para dois cliques não passarem juntos.
-----------------------------------------------------------------------------------------------------------------------------------------
local BankLocks = {}
-----------------------------------------------------------------------------------------------------------------------------------------
-- NOW
-----------------------------------------------------------------------------------------------------------------------------------------
function Now()
    return osTime()
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- TODAY
-- Dia inteiro desde a época, usado como chave do gráfico de saldo.
-----------------------------------------------------------------------------------------------------------------------------------------
function Today()
    return mathFloor(osTime() / 86400)
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- NORMALIZEAMOUNT
-- Dinheiro no jogo é sempre inteiro positivo: centavo não existe.
-----------------------------------------------------------------------------------------------------------------------------------------
function NormalizeAmount(Value)
    local Number = tonumber(Value)
    if not Number or Number ~= Number or Number == math.huge or Number == -math.huge then return false end

    Number = mathFloor(Number)
    return Number > 0 and Number or false
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- TRUTHY
-- Coluna de flag do MySQL. Dependendo da versão do driver ela chega como
-- número (1) ou como booleano (true), e comparar só com 1 fazia toda empresa
-- ser lida como conta pessoal.
-----------------------------------------------------------------------------------------------------------------------------------------
function Truthy(Value)
    return Value == true or tonumber(Value) == 1
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- LIMITTEXT
-----------------------------------------------------------------------------------------------------------------------------------------
function LimitText(Value, Maximum)
    if Value == nil then return nil end

    local Text = tostring(Value)
    return #Text > Maximum and Text:sub(1, Maximum) or Text
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- ACQUIRE
-----------------------------------------------------------------------------------------------------------------------------------------
function Acquire(Passport)
    if BankLocks[Passport] then return false end

    BankLocks[Passport] = true
    return true
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- RELEASE
-----------------------------------------------------------------------------------------------------------------------------------------
function Release(Passport)
    BankLocks[Passport] = nil
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- CLEANUP
-----------------------------------------------------------------------------------------------------------------------------------------
Framework.OnPlayerDropped(function(Passport)
    BankLocks[Passport] = nil
end)
