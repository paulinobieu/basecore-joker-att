-----------------------------------------------------------------------------------------------------------------------------------------
-- NETEVENTS
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterNetEvent("core-booster:OpenPanel", function(Data)
    OpenPanel(Data)
end)
-----------------------------------------------------------------------------------------------------------------------------------------
-- ONRESOURCESTOP
-----------------------------------------------------------------------------------------------------------------------------------------
AddEventHandler("onResourceStop", function(Resource)
    if Resource ~= GetCurrentResourceName() then
        return
    end

    ClosePanel()

    SetNuiFocus(false, false)
    SetNuiFocusKeepInput(false)
end)
