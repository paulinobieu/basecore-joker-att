-----------------------------------------------------------------------------------------------------------------------------------------
-- NOTIFY
-----------------------------------------------------------------------------------------------------------------------------------------
function Functions.Notify(Source,Title,Message,Color,Time)
	if Source then
		TriggerClientEvent("Notify",Source,Title,Message,Color,Time)
	else
		TriggerClientEvent("Notify",-1,Title,Message,Color,Time)
	end
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- ANNOUNCE
-----------------------------------------------------------------------------------------------------------------------------------------
function Functions.Announce(Source,Title,Message,Time)
	if Source then
		TriggerClientEvent("Notify",Source,Title,Message,"helicrash",Time or 10000)
	else
		TriggerClientEvent("Notify",-1,Title,Message,"helicrash",Time or 10000)
	end
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- LOG
-----------------------------------------------------------------------------------------------------------------------------------------
function Functions.Log(Category,Data)
	if GetResourceState("core_logs") == "started" then
		exports["core_logs"]:AddLog(Category,Data)
	end
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- WEBHOOK
-----------------------------------------------------------------------------------------------------------------------------------------
function Functions.Webhook(Url,Embed)
	if not Url or Url == "" then
		return false
	end

	PerformHttpRequest(Url,function() end,"POST",json.encode({ embeds = { Embed } }),{ ["Content-Type"] = "application/json" })
end
