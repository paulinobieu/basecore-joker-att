function Avatar() {
	const avatar = useEscStore((state) => state.player.avatar);
	const { imageUrl, isImageValid } = useImageValidation(avatar);

	return (
		<div className="relative">
			<div className="maskAvatar relative z-10 flex size-10 items-center justify-center rounded-md border border-white/[.11] border-solid">
				<img
					src={isImageValid ? imageUrl : FallbackAvatar}
					alt="avatar"
					className="absolute z-0 size-full rounded-md object-cover"
				/>
			</div>
			<div className="absolute top-0 right-0 z-10 size-[.4375rem] rounded-full bg-[#C8FF49]" />
		</div>
	);
}

