-----------------------------------------------------------------------------------------------------------------------------------------
-- FUNCTIONS
-----------------------------------------------------------------------------------------------------------------------------------------
Functions = {}
-----------------------------------------------------------------------------------------------------------------------------------------
-- PASSPORT
-----------------------------------------------------------------------------------------------------------------------------------------
function Functions.Passport(source)
	return vRP.Passport(source)
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- SOURCE
-----------------------------------------------------------------------------------------------------------------------------------------
function Functions.Source(Passport)
	return vRP.Source(Passport)
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- IDENTITY
-----------------------------------------------------------------------------------------------------------------------------------------
function Functions.Identity(Passport)
	return vRP.Identity(Passport) or false
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- FULLNAME
-----------------------------------------------------------------------------------------------------------------------------------------
function Functions.FullName(Passport)
	return vRP.FullName(Passport)
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- NOTIFY
-----------------------------------------------------------------------------------------------------------------------------------------
function Functions.Notify(Source,Title,Message,Kind,Time)
	if Source then
		TriggerClientEvent("Notify",Source,Title,Message,Kind or "amarelo",Time or 5000)
	else
		TriggerEvent("Notify",Title,Message,Kind or "amarelo",Time or 5000)
	end
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- HASPERMISSION
-----------------------------------------------------------------------------------------------------------------------------------------
function Functions.HasPermission(Passport,Permission)
	if not Passport then
		return false
	end

	if not Permission then
		return true
	end

	if type(Permission) == "table" then
		return vRP.HasTable(Passport,Permission) and true or false
	end

	local Group,Level = Permission:match("^(.+)@(%d+)$")
	if Group then
		return vRP.HasGroup(Passport,Group,tonumber(Level)) and true or false
	end

	return (vRP.HasPermission(Passport,Permission) or vRP.HasGroup(Passport,Permission,1)) and true or false
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- PALETTE
-----------------------------------------------------------------------------------------------------------------------------------------
function Functions.HexToRgb(Hex)
	if type(Hex) ~= "string" then return 55,218,230 end
	Hex = Hex:gsub("#","")
	if #Hex ~= 6 then return 55,218,230 end
	return tonumber(Hex:sub(1,2),16) or 55,tonumber(Hex:sub(3,4),16) or 218,tonumber(Hex:sub(5,6),16) or 230
end
