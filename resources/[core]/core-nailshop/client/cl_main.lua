CreateThread(function()
    while not playerLoaded or next(PlayerNailDatas) == nil do
        Wait(1000)
    end

    while true do
        Wait(500)
        local ped = cache.ped

        if not DoesEntityExist(ped) then
            Wait(1000)
            goto continue
        end

        local myServerId = cache.serverId

        for serverId, nailData in pairs(PlayerNailDatas) do
            if tonumber(serverId) == tonumber(myServerId) then goto next_player end
            if not nailData or not next(nailData) then goto next_player end

            local targetPlayer = GetPlayerFromServerId(tonumber(serverId))

            if targetPlayer == -1 or not NetworkIsPlayerActive(targetPlayer) then
                Debug('info', 'Skipping inactive player %d', serverId)

                if PlayerNails[serverId] then
                    for boneId, obj in pairs(PlayerNails[serverId]) do
                        if DoesEntityExist(obj) then
                            DeleteObject(obj)
                        end
                    end
                end
                PlayerNails[serverId] = nil
                goto next_player
            end

            local targetPed = GetPlayerPed(targetPlayer)

            if not DoesEntityExist(targetPed) or targetPed == 0 then
                Debug('info', 'Skipping non-existent ped for player %d', serverId)

                if PlayerNails[serverId] then
                    for boneId, obj in pairs(PlayerNails[serverId]) do
                        if DoesEntityExist(obj) then
                            DeleteObject(obj)
                        end
                    end
                end
                PlayerNails[serverId] = nil
                goto next_player
            end

            local myCoords = GetEntityCoords(cache.ped)
            local targetCoords = GetEntityCoords(ped)

            local distance = #(myCoords - targetCoords)

            if distance <= STREAM_DISTANCE_CREATE then
                if not PlayerNails[serverId] then
                    Debug('info', 'Player %d is in range (%.1f), creating nails', serverId, distance)
                    CreateNailsForPlayer(tonumber(serverId), ped, nailData)
                end
            else
                if PlayerNails[serverId] then
                    for boneId, obj in pairs(PlayerNails[serverId]) do
                        if DoesEntityExist(obj) then
                            DeleteObject(obj)
                        end
                    end
                end
                PlayerNails[serverId] = nil
            end

            ::next_player::
        end

        ::continue::
    end
end)

