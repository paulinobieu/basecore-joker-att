--- Cleans up nail objects for a specific player
--- @param customerId number
local function CleanupPlayerNails(customerId)
    if PlayerNails[tostring(customerId)] then
        for boneId, obj in pairs(PlayerNails[tostring(customerId)]) do
            if DoesEntityExist(obj) then
                DeleteObject(obj)
            end
        end
        PlayerNails[tostring(customerId)] = nil
        Debug('info', 'Cleaned up nails for player %d', customerId)
    end
end

--- Creates nails for a player based on nail data
--- @param targetId number Server ID of the customer
--- @param _ number Ped entity handle
--- @param nailData table Nail data from StateBag
function CreateNailsForPlayer(targetId, _, nailData)
    local customerId = targetId
    local myPed = cache.ped
    local ped = GetPlayerPed(GetPlayerFromServerId(customerId))
    if not DoesEntityExist(ped) then
        Debug('warning', 'Ped does not exist for preview, customer ID: %d', customerId)
        return
    end

    local dist = #(GetEntityCoords(myPed) - GetEntityCoords(ped))
    if dist > 50.0 or (dist == 0.0 and customerId ~= cache.serverId) then
        Debug('warning', 'Target too far away for preview, customer ID: %d', customerId)
        return
    end

    Debug('info', 'Creating nails for player %d', customerId)

    if not PlayerNails[tostring(customerId)] then
        PlayerNails[tostring(customerId)] = {}
    end

    local existing = PlayerNails[tostring(customerId)]
    local nailGroups = {}
    for boneId, data in pairs(nailData) do
        local objectHash = nil

        if data.lengthNail ~= 'small_french' and data.lengthNail ~= 'cut_french' then
            objectHash = GetHashKey('qua_nail_'.. data.lengthNail ..'_' .. data.patternNail)
        else
            local length = data.lengthNail == 'small_french' and 'small' or 'cut'
            objectHash = GetHashKey('qua_nail_nude_notint_' .. length)
        end


        local key = data.lengthNail .. '_' .. data.patternNail
        if not nailGroups[key] then
            nailGroups[key] = {
                objectHash = objectHash,
                nails = {}
            }
        end
        table.insert(nailGroups[key].nails, { boneId = boneId, data = data })
    end

    local entityCoords = GetEntityCoords(ped)
    for key, group in pairs(nailGroups) do
        if not HasModelLoaded(group.objectHash) then
            RequestModel(group.objectHash)
            while not HasModelLoaded(group.objectHash) do Wait(10) end
        end

        for _, nailInfo in ipairs(group.nails) do
            local boneId = nailInfo.boneId
            local data = nailInfo.data

            if existing[boneId] then
                if DoesEntityExist(existing[boneId]) then
                    DeleteObject(existing[boneId])
                end
                existing[boneId] = nil
            end

            local boneIdNum = tonumber(boneId)
            if not boneIdNum then
                Debug('warning', 'Invalid bone ID %s', tostring(boneId))
                goto continue
            end

            local position = nil

            if data.lengthNail == 'small_french' or data.lengthNail == 'cut_french' then
                position = nailsPosition['small_french'][boneIdNum]
            else
                position = nailsPosition[data.lengthNail .. '_nails'][boneIdNum]
            end
            if not position then
                Debug('warning', 'No position data for bone %d with length %s', boneIdNum, data.lengthNail)
                goto continue
            end

            local object = CreateObject(group.objectHash, entityCoords.x, entityCoords.y, entityCoords.z, false, true, false)

            if not DoesEntityExist(object) then
                Debug('warning', 'Failed to create object for bone %d with length %s', boneIdNum, data.lengthNail)
                goto continue
            end

            AttachEntityToEntity(
                object, ped, boneIdNum,
                position.offset.x, position.offset.y, position.offset.z,
                position.rotation.x, position.rotation.y, position.rotation.z,
                true, true, false, true, 1, true
            )

            if data.lengthNail ~= 'small_french' and data.lengthNail ~= 'cut_french' then
                SetObjectTextureVariation(object, data.colorNail)
            end

            Debug('info', 'Created nail object for bone %s (object: %d)', boneId, object)

            PlayerNails[tostring(customerId)][tostring(boneId)] = object
            ::continue::
        end

        SetModelAsNoLongerNeeded(group.objectHash)
    end

    Debug('success', 'Successfully created all nails for player %d', customerId)
end

