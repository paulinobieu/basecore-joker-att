    local dist = #(GetEntityCoords(myPed) - GetEntityCoords(ped))
    if dist > 50.0 or (dist == 0.0 and customerId ~= cache.serverId) then
        Debug('warning', 'Target too far away for preview, customer ID: %d', customerId)
        return
    end

    Debug('info', 'Previewing nail design for customer %d', customerId)

    if not PlayerNails[tostring(customerId)] then
        PlayerNails[tostring(customerId)] = {}
    end

    local existing = PlayerNails[tostring(customerId)]

    for _, fingerData in pairs(data) do
        if existing[tostring(fingerData.boneId)] then
            if DoesEntityExist(existing[tostring(fingerData.boneId)]) then
                DeleteObject(existing[tostring(fingerData.boneId)])
            end
            existing[tostring(fingerData.boneId)] = nil
        end
    end

    for _, fingerData in pairs(data) do
        local objectHash = nil

        if fingerData.lengthNail ~= 'small_french' and fingerData.lengthNail ~= 'cut_french' then
            objectHash = GetHashKey('qua_nail_'.. fingerData.lengthNail ..'_' .. fingerData.patternNail)

            if not HasModelLoaded(objectHash) then
                RequestModel(objectHash)
                while not HasModelLoaded(objectHash) do Wait(10) end
            end
        else
            local length = fingerData.lengthNail == 'small_french' and 'small' or 'cut'
            objectHash = GetHashKey('qua_nail_nude_notint_' .. length)

            if not HasModelLoaded(objectHash) then
                RequestModel(objectHash)
                while not HasModelLoaded(objectHash) do Wait(10) end
            end
        end

        if not objectHash then
            Debug('warning', 'No object hash found for preview, customer ID: %d', customerId)
            return
        end

        local position = nil

        if fingerData.lengthNail == 'small_french' or fingerData.lengthNail == 'cut_french' then
            position = nailsPosition['small_french'][fingerData.boneId]
        else
            position = nailsPosition[fingerData.lengthNail .. '_nails'][fingerData.boneId]
        end

        local object = CreateObject(objectHash, 0.0, 0.0, 0.0, false, true, false)

        AttachEntityToEntity(
            object, ped, tonumber(fingerData.boneId),
            position.offset.x, position.offset.y, position.offset.z,
            position.rotation.x, position.rotation.y, position.rotation.z,
            true, true, false, true, 1, true
        )

        if fingerData.lengthNail ~= 'small_french' or fingerData.lengthNail ~= 'cut_french' then
            SetObjectTextureVariation(object, fingerData.colorNail)
        end

        PlayerNails[tostring(customerId)][tostring(fingerData.boneId)] = object
        SetModelAsNoLongerNeeded(objectHash)
    end

    Debug('success', 'Preview nail design applied for customer %d', customerId)
end)

RegisterNetEvent(Scriptname .. ':client:clearFingerDesign', function(customerId, fingerId, hand)
    local ped = GetPlayerPed(GetPlayerFromServerId(customerId))
    if not DoesEntityExist(ped) then
        Debug('warning', 'Ped does not exist for clear finger design, customer ID: %d', customerId)
        return
    end

    if not fingerId or not hand then
        Debug('warning', 'Invalid fingerId or hand for clear finger design, customer ID: %d', customerId)
        return
    end

    Debug('info', 'Clearing finger design for customer %d (fingerId: %s, hand: %s)', customerId, tostring(fingerId), hand)

    local finger = Config.FingerBones[hand .. '_' .. fingerId]
    if not finger then
        Debug('warning', 'Invalid finger bone for hand %s, id %s', hand, tostring(fingerId))
        return
    end

    if not PlayerNails[tostring(customerId)] then
        Debug('info', 'No nail objects found for customer %d', customerId)
        return
    end

    local existing = PlayerNails[tostring(customerId)]
    local boneIdStr = tostring(finger)

    if existing[boneIdStr] then
        if DoesEntityExist(existing[boneIdStr]) then
            DeleteObject(existing[boneIdStr])
            Debug('info', 'Deleted nail object for bone %d (fingerId: %s, hand: %s) for customer %d', finger, tostring(fingerId), hand, customerId)
        end
        existing[boneIdStr] = nil

        if not next(existing) then
            PlayerNails[tostring(customerId)] = nil
            Debug('info', 'All nail objects cleared for customer %d', customerId)
        end
    else
        Debug('info', 'No nail object found for bone %d (fingerId: %s, hand: %s) for customer %d', finger, tostring(fingerId), hand, customerId)
    end

    Debug('success', 'Finger design cleared for customer %d', customerId)
end)

