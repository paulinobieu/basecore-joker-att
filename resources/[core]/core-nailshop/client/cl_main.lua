    if not newPed or newPed == 0 then return end

    if oldPed and oldPed == newPed then return end

    local playerId = GetPlayerServerId(PlayerId())

    Debug('info', 'Ped changed for player %d (old: %d, new: %d)', playerId, oldPed or 0, newPed)

