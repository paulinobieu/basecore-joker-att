local Proxy = module("vrp","lib/Proxy")
vRP = Proxy.getInterface("vRP")
-----------------------------------------------------------------------------------------------------------------------------------------
-- COMMANDS
-----------------------------------------------------------------------------------------------------------------------------------------
for _, cmd in ipairs(PedScale.Commands) do
    RegisterCommand(cmd, function(source)
        if source <= 0 then return end
        if not vRP.Passport(source) then return end

        TriggerClientEvent("core-pedscale:toggle", source)
    end)
end

