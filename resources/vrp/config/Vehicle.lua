-----------------------------------------------------------------------------------------------------------------------------------------
-- HELPERS
-----------------------------------------------------------------------------------------------------------------------------------------
local function safeGetInfo(Name)
local ok, info = pcall(function() return exports['core-vehicles']:getVehicleInfo(Name) end)
return ok and info or nil
end

local function safeGetList()
local ok, list = pcall(function() return exports['core-vehicles']:getVehicleList() end)
return ok and list or {}
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- VEHICLELIST
-----------------------------------------------------------------------------------------------------------------------------------------
function VehicleList()
return safeGetList()
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- VEHICLEEXIST
-----------------------------------------------------------------------------------------------------------------------------------------
function VehicleExist(Name)
return safeGetInfo(Name) or false
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- VEHICLENAME
-----------------------------------------------------------------------------------------------------------------------------------------
function VehicleName(Name)
local info = safeGetInfo(Name)
return info and info.name or "Desconhecido"
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- VEHICLEWEIGHT
-----------------------------------------------------------------------------------------------------------------------------------------
function VehicleWeight(Name)
local info = safeGetInfo(Name)
return info and info.weights and info.weights.trunk or 0
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- VEHICLEPRICE
-----------------------------------------------------------------------------------------------------------------------------------------
function VehiclePrice(Name)
local info = safeGetInfo(Name)
return info and info.price or 0
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- VEHICLEMODE
-----------------------------------------------------------------------------------------------------------------------------------------
function VehicleMode(Name)
local info = safeGetInfo(Name)
return info and info.mode or false
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- VEHICLEGEMSTONE
-----------------------------------------------------------------------------------------------------------------------------------------
function VehicleGemstone(Name)
local info = safeGetInfo(Name)
return info and info.gemstone or 0
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- VEHICLECLASS
-----------------------------------------------------------------------------------------------------------------------------------------
function VehicleClass(Name)
local info = safeGetInfo(Name)
return info and info.class or "Desconhecido"
end
-----------------------------------------------------------------------------------------------------------------------------------------
-- VEHICLESTOCK
-----------------------------------------------------------------------------------------------------------------------------------------
function VehicleStock(Name)
local info = safeGetInfo(Name)
return info and info.stock or 999999
end-----------------------------------------------------------------------------------------------------------------------------------------
-- EXPORTS
-----------------------------------------------------------------------------------------------------------------------------------------
exports("VehicleList",VehicleList)
exports("VehicleExist",VehicleExist)
exports("VehicleName",VehicleName)
exports("VehicleWeight",VehicleWeight)
exports("VehiclePrice",VehiclePrice)
exports("VehicleMode",VehicleMode)
exports("VehicleGemstone",VehicleGemstone)
exports("VehicleClass",VehicleClass)
exports("VehicleStock",VehicleStock)
